if (process.platform === 'win32') await extractZip(archive, { dir: extracted });
else await run('tar', ['-xzf', archive, '-C', extracted]);
const [nodeFolder] = await fs.readdir(extracted);
const nodeDistribution = path.join(extracted, nodeFolder);
const runtimeDir = path.join(resources, 'runtime');
await fs.mkdir(runtimeDir, { recursive: true });
const nodeBinary = path.join(runtimeDir, process.platform === 'win32' ? 'node.exe' : 'node');
await fs.copyFile(path.join(nodeDistribution, process.platform === 'win32' ? 'node.exe' : 'bin/node'), nodeBinary);
await fs.copyFile(path.join(nodeDistribution, 'LICENSE'), path.join(runtimeDir, 'LICENSE'));
if (process.platform !== 'win32') await fs.chmod(nodeBinary, 0o755);
const { prepareWindowsCrt } = await import('./prepare-windows-crt.mjs');
await prepareWindowsCrt(resources);
const runtimeIdentity = JSON.parse(await capture(nodeBinary, ['-p', 'JSON.stringify({version:process.version,platform:process.platform,arch:process.arch})']));

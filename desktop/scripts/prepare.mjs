function run(executable, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, { stdio: 'inherit', windowsHide: true, ...options });
    child.once('error', reject);
    child.once('exit', (code, signal) => code === 0 ? resolve() : reject(new Error(`${path.basename(executable)} exited with ${code ?? signal}`)));
  });
}
async function capture(executable, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, { stdio: ['ignore', 'pipe', 'inherit'], windowsHide: true, ...options });
    let output = ''; child.stdout.setEncoding('utf8'); child.stdout.on('data', value => { output += value; });
    child.once('error', reject);
    child.once('exit', code => code === 0 ? resolve(output.trim()) : reject(new Error(`${path.basename(executable)} exited with ${code}`)));
  });
}
async function sha256(file) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk);
  return hash.digest('hex');
}
async function download(url, output, expected) {
  if (await fs.access(output).then(() => true, () => false)) {
    if (await sha256(output) === expected) return;
    await fs.rm(output);
  }
  console.log(`Downloading ${path.basename(output)}`);
  const response = await fetch(url, { signal: AbortSignal.timeout(10 * 60_000) });
  if (!response.ok || !response.body) throw new Error(`Download failed: ${url} (${response.status})`);
  const partial = `${output}.partial`;
  try {
    await pipeline(Readable.fromWeb(response.body), createWriteStream(partial));
    if (await sha256(partial) !== expected) throw new Error(`SHA-256 mismatch: ${path.basename(output)}`);
    await fs.rename(partial, output);
  } catch (error) { await fs.rm(partial, { force: true }); throw error; }
}
const relative = target => path.relative(resources, target).split(path.sep).join('/');
await fs.access(path.join(root, 'backend/dist/server.js'));

const require = createRequire(import.meta.url);
const SLUG = /^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/;
const WORKSPACE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const SESSION = /^[a-f0-9-]{36}$/;
const SEGMENT = /^segment-\d{8,20}\.ts$/;
const EPOCH = /^[a-zA-Z0-9_-][a-zA-Z0-9_.:-]{7,95}$/;
const MIME = { '.m3u8': 'application/vnd.apple.mpegurl', '.ts': 'video/mp2t' };
class HttpError extends Error { constructor(status, message) { super(message); this.status = status; } }
const fail = (status, message) => { throw new HttpError(status, message); };
const digest = bytes => createHash('sha256').update(bytes).digest('hex');

/** Provisioned only by the service administrator after verifying workspace
 * ownership. Never accept this registry from a public request or browser. */
export async function readTenantRegistry(filename) {
  if (typeof filename !== 'string' || !path.isAbsolute(filename)) throw new Error('Tenant settings require an absolute private file path.');
  let handle;
  try {
    if ((await fs.lstat(filename)).isSymbolicLink()) throw new Error();
    handle = await fs.open(filename, constants.O_RDONLY | constants.O_NOFOLLOW);
    const stat = await handle.stat();
    if (!stat.isFile() || stat.size < 1 || stat.size > 1024 * 1024 || (stat.mode & 0o077) !== 0
      || process.getuid && stat.uid !== process.getuid()) throw new Error();
    const bytes = await handle.readFile(); if (bytes.length > 1024 * 1024) throw new Error();
    const value = JSON.parse(bytes.toString('utf8'));
    if (!value || value.version !== 1 || Object.keys(value).some(key => !['version', 'tenants'].includes(key)) || !Array.isArray(value.tenants)) throw new Error();
    return value.tenants;
  } catch { throw new Error('Tenant settings must be a bounded, owner-only regular file with valid version 1 JSON; symlinks are not allowed.'); }
  finally { await handle?.close(); }
}

function credentials(input, tenantMode) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) throw new Error('Invalid relay tenant settings.');
  if (tenantMode && (Object.keys(input).some(key => !['workspaceId', 'pushToken', 'viewerToken', 'allowedSlugs', 'privateSlugs'].includes(key)) || !WORKSPACE.test(input.workspaceId ?? ''))) throw new Error('A canonical workspace UUID is required.');
  const { pushToken, viewerToken } = input;
  if (typeof pushToken !== 'string' || Buffer.byteLength(pushToken) < 32 || Buffer.byteLength(pushToken) > 256 || /[^\x21-\x7e]/.test(pushToken)) throw new Error('A publishing token of 32–256 printable bytes is required.');
  const tokenHash = createHash('sha256').update(pushToken).digest();
  if (input.allowedSlugs !== undefined && (!Array.isArray(input.allowedSlugs) || input.allowedSlugs.length > 8)) throw new Error('Invalid allowed relay slug.');
  const allowed = input.allowedSlugs ? new Set(input.allowedSlugs) : null;
  if (tenantMode && !allowed || allowed && (!allowed.size || allowed.size !== input.allowedSlugs.length || [...allowed].some(slug => typeof slug !== 'string' || !SLUG.test(slug)))) throw new Error('Invalid allowed relay slug.');
  if (input.privateSlugs !== undefined && (!Array.isArray(input.privateSlugs) || input.privateSlugs.length > 8)) throw new Error('Private output slugs must be valid allowed relay slugs.');
  const privateSlugs = new Set(input.privateSlugs ?? []);
  if (privateSlugs.size !== (input.privateSlugs?.length ?? 0) || [...privateSlugs].some(slug => typeof slug !== 'string' || !SLUG.test(slug) || allowed && !allowed.has(slug))) throw new Error('Private output slugs must be valid allowed relay slugs.');
  if ((privateSlugs.size || viewerToken !== undefined) && (typeof viewerToken !== 'string' || !/^[\x21-\x7e]{32,256}$/.test(viewerToken)
    || timingSafeEqual(tokenHash, createHash('sha256').update(viewerToken).digest()))) throw new Error('Private outputs require a distinct viewer token of 32–256 printable characters.');
  return { workspaceId: tenantMode ? input.workspaceId : null, tokenHash, viewerToken, viewerHash: privateSlugs.size ? createHash('sha256').update(viewerToken).digest() : null, allowed, privateSlugs };
}

/** Deliberately accepts only the unencrypted, single-rendition MPEG-TS output
 * generated by Lumen. No remote URLs, keys, nested paths or arbitrary HLS tags. */
export function parsePlaylist(bytes) {
  const text = bytes.toString('utf8');
  if (text.includes('\0') || !text.startsWith('#EXTM3U\n')) fail(400, 'Invalid media playlist.');
  const lines = text.split(/\r?\n/), segments = [];
  let sequence, target, expectingSegment = false;
  for (const raw of lines) {
    const line = raw.trim(); if (!line) continue;
    if (line.startsWith('#')) {
      if (!/^#(?:EXTM3U|EXT-X-VERSION:\d+|EXT-X-TARGETDURATION:\d+|EXT-X-MEDIA-SEQUENCE:\d+|EXT-X-DISCONTINUITY-SEQUENCE:\d+|EXT-X-INDEPENDENT-SEGMENTS|EXT-X-DISCONTINUITY|EXT-X-PROGRAM-DATE-TIME:[0-9T:.+Z-]+|EXTINF:\d+(?:\.\d+)?,|EXT-X-ENDLIST)$/.test(line)) fail(400, 'Unsupported media playlist tag.');
      if (line.startsWith('#EXT-X-TARGETDURATION:')) target = Number(line.split(':')[1]);
      if (line.startsWith('#EXT-X-MEDIA-SEQUENCE:')) sequence = Number(line.split(':')[1]);
      if (line.startsWith('#EXTINF:')) { const duration = Number(line.slice(8, -1)); if (!(duration > 0 && duration <= 15) || expectingSegment) fail(400, 'Invalid segment duration.'); expectingSegment = true; }
      continue;
    }
    if (!SEGMENT.test(line) || !expectingSegment || segments.includes(line)) fail(400, 'Only local generated segments are accepted.');
    segments.push(line); expectingSegment = false;
  }
  if (!Number.isSafeInteger(sequence) || !(sequence >= 0) || !(target >= 1 && target <= 15) || expectingSegment || !segments.length || segments.length > 12) fail(400, 'Invalid live window.');
  const numbers = segments.map(name => BigInt(name.slice(8, -3)));
  if (numbers.some((value, i) => i > 0 && value <= numbers[i - 1])) fail(400, 'Segments must be increasing.');
  return { text, sequence, segments, latest: numbers.at(-1) };
}

async function readBody(req, limit) {
  const declared = Number(req.headers['content-length']);
  if (Number.isFinite(declared) && declared > limit) { req.resume(); fail(413, 'Upload is too large.'); }
  const chunks = []; let size = 0;
  for await (const chunk of req) { size += chunk.length; if (size > limit) { req.resume(); fail(413, 'Upload is too large.'); } chunks.push(chunk); }
  return Buffer.concat(chunks);
}
async function atomic(filename, bytes) {
  const temporary = `${filename}.${randomUUID()}.tmp`;
  try { await fs.writeFile(temporary, bytes, { flag: 'wx', mode: 0o600 }); await fs.rename(temporary, filename); }
  finally { await fs.unlink(temporary).catch(() => {}); }
}
function send(res, status, body, headers = {}) {
  const bytes = typeof body === 'string' ? Buffer.from(body) : Buffer.from(JSON.stringify(body));
  res.writeHead(status, { 'Content-Type': typeof body === 'string' ? 'text/plain; charset=utf-8' : 'application/json; charset=utf-8', 'Content-Length': bytes.length, 'Cache-Control': 'no-store', ...headers }); res.end(bytes);
}

export async function createWatchRelay(options) {
  const { dataDir } = options;
  if (!dataDir) throw new Error('A private data directory is required.');
  const root = path.resolve(dataDir), tenantMode = options.tenants !== undefined, tenants = new Map();
  let legacy = null;
  if (tenantMode) {
    if (!Array.isArray(options.tenants) || !options.tenants.length || options.tenants.length > 256) throw new Error('Tenant mode requires 1–256 explicitly registered workspaces.');
    const hashes = new Set();
    for (const input of options.tenants) {
      const tenant = credentials(input, true);
      if (tenants.has(tenant.workspaceId)) throw new Error('Duplicate workspace registration.');
      for (const hash of [tenant.tokenHash.toString('hex'), ...(tenant.viewerToken ? [digest(tenant.viewerToken)] : [])]) {
        if (hashes.has(hash)) throw new Error('Workspace credentials must be unique and cannot be reused.'); hashes.add(hash);
      }
      tenants.set(tenant.workspaceId, tenant);
    }
  } else legacy = credentials(options, false);
  const sessionMs = options.outputSessionMs ?? 3600000;
  if (!Number.isSafeInteger(sessionMs) || sessionMs < 1000 || sessionMs > 3600000) throw new Error('Output sessions must expire within one hour.');
  const maxStreams = options.maxStreams ?? 8, maxBytes = options.maxWindowBytes ?? 64 * 1024 * 1024, maxSegment = options.maxSegmentBytes ?? 8 * 1024 * 1024;
  const maxStreamsPerTenant = options.maxStreamsPerTenant ?? 2;
  if (!Number.isSafeInteger(maxStreamsPerTenant) || maxStreamsPerTenant < 1 || maxStreamsPerTenant > 8) throw new Error('Workspace stream quota must be from 1 to 8.');
  const staleMs = options.staleMs ?? 18000, offlineTtlMs = options.offlineTtlMs ?? 120000, now = options.now ?? Date.now;
  const streams = new Map(), locks = new Map(), tenantUploads = new Map(); let uploading = 0;
  const streamKey = (tenant, slug) => tenant.workspaceId ? `${tenant.workspaceId}/${slug}` : slug;
  const route = (kind, tenant, slug) => `/${kind}/${tenant.workspaceId ? `${tenant.workspaceId}/` : ''}${slug}`;
  await fs.mkdir(root, { recursive: true, mode: 0o700 });
  // Restart always comes back Offline; stale playlists are never advertised.
  // Keep the bounded epoch fence so an old publisher cannot resurrect a session.
  async function restore(folder, tenant) {
    for (const entry of await fs.readdir(folder, { withFileTypes: true })) {
      if (!entry.isDirectory() || !SLUG.test(entry.name) || tenant.allowed && !tenant.allowed.has(entry.name)) continue;
      try {
        const record = JSON.parse(await fs.readFile(path.join(folder, entry.name, 'session.json'), 'utf8'));
        streams.set(streamKey(tenant, entry.name), { epochs: Array.isArray(record.epochs) ? record.epochs.filter(value => typeof value === 'string' && EPOCH.test(value)).slice(-64) : [], session: null });
        for (const child of await fs.readdir(path.join(folder, entry.name), { withFileTypes: true })) if (child.isDirectory() && SESSION.test(child.name)) await fs.rm(path.join(folder, entry.name, child.name), { recursive: true, force: true });
      } catch { /* Invalid leftovers are never public or used as paths. */ }
    }
  }
  if (tenantMode) {
    for (const tenant of tenants.values()) {
      const folder = path.join(root, tenant.workspaceId);
      try { const info = await fs.lstat(folder); if (!info.isDirectory() || info.isSymbolicLink()) throw new Error(); await restore(folder, tenant); }
      catch (error) { if (error.code !== 'ENOENT') throw new Error('A workspace media directory could not be read safely.'); }
    }
  } else await restore(root, legacy);
  const authorize = (req, tenant) => {
    const authorization = req.headers.authorization;
    if (typeof authorization !== 'string' || !authorization.startsWith('Bearer ') || !timingSafeEqual(tenant.tokenHash, createHash('sha256').update(authorization.slice(7)).digest())) fail(401, 'Publishing authorization required.');
  };
  const cookieName = (tenant, slug) => `lumen_output_${tenant.workspaceId ? `${tenant.workspaceId}_` : ''}${slug}`;
  const signViewerSession = (tenant, slug, value) => createHmac('sha256', tenant.viewerToken).update(`output:${streamKey(tenant, slug)}:${value}`).digest('hex');
  const viewerKeyAccepted = (req, tenant) => {
    const authorization = req.headers.authorization;
    return !!tenant.viewerHash && typeof authorization === 'string' && authorization.startsWith('Bearer ')
      && timingSafeEqual(tenant.viewerHash, createHash('sha256').update(authorization.slice(7)).digest());
  };
  const viewerCookieAccepted = (req, tenant, slug) => {
    const name = cookieName(tenant, slug);
    const cookies = typeof req.headers.cookie === 'string' ? req.headers.cookie.split(';').map(value => value.trim()).filter(value => value.startsWith(`${name}=`)) : [];
    if (cookies.length !== 1) return false;
    const value = cookies[0].slice(name.length + 1), match = /^v1\.(\d{1,13})\.([a-f0-9]{32})\.([a-f0-9]{64})$/.exec(value);
    if (!match || !Number.isSafeInteger(Number(match[1])) || Number(match[1]) <= now()) return false;
    const expected = Buffer.from(signViewerSession(tenant, slug, `v1.${match[1]}.${match[2]}`), 'hex');
    return timingSafeEqual(expected, Buffer.from(match[3], 'hex'));
  };
  const authorizeViewer = (req, tenant, slug) => {
    if (tenant.privateSlugs.has(slug) && !viewerKeyAccepted(req, tenant) && !viewerCookieAccepted(req, tenant, slug)) fail(401, 'Output access required. Open a current share link.');
  };
  const outputHeaders = (tenant, slug) => tenant.privateSlugs.has(slug) ? { 'Cache-Control': 'private, no-store, max-age=0', Vary: 'Cookie, Authorization' } : {};
  const validSlug = (slug, tenant) => { if (!tenant || !SLUG.test(slug) || tenant.allowed && !tenant.allowed.has(slug)) fail(404, 'Not found.'); };
  const persist = async (slug, record) => { const folder = path.join(root, slug); await fs.mkdir(folder, { recursive: true, mode: 0o700 }); await atomic(path.join(folder, 'session.json'), Buffer.from(JSON.stringify({ epochs: record.epochs }))); };
  const state = record => {
    const current = record?.session;
    if (!current || current.endedAt !== undefined || current.lastProgressAt !== undefined && now() - current.lastProgressAt > staleMs || current.lastProgressAt === undefined && now() - current.startedAt > staleMs) return 'offline';
    return current.playlist ? 'live' : 'connecting';
  };
  const serial = async (slug, fn) => {
    const previous = locks.get(slug) ?? Promise.resolve();
    const next = previous.catch(() => {}).then(fn); locks.set(slug, next);
    try { return await next; } finally { if (locks.get(slug) === next) locks.delete(slug); }
  };
  const cleanup = async () => {
    for (const [slug, record] of streams) await serial(slug, async () => {
      const current = record.session;
      if (current && state(record) === 'offline' && now() - (current.endedAt ?? current.lastProgressAt ?? current.startedAt) > offlineTtlMs) {
        record.session = null; await fs.rm(path.join(root, slug, current.id), { recursive: true, force: true });
      }
    });
  };
  const interval = setInterval(() => { void cleanup().catch(() => {}); }, Math.min(30000, offlineTtlMs)); interval.unref();
  const hlsBundle = require.resolve('hls.js/dist/hls.min.js');
  const publicDir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'public');
  const server = http.createServer({ maxHeaderSize: 8192, requestTimeout: 20000, headersTimeout: 10000 }, async (req, res) => {
    res.setHeader('X-Content-Type-Options', 'nosniff'); res.setHeader('Referrer-Policy', 'no-referrer');
    res.setHeader('Content-Security-Policy', "default-src 'self'; script-src 'self'; style-src 'self'; media-src 'self' blob:; connect-src 'self'; worker-src 'self' blob:; img-src 'self' data:; object-src 'none'; base-uri 'none'; frame-ancestors 'none'");
    res.setHeader('Permissions-Policy', 'camera=(), microphone=(), geolocation=()');
    try {
      const rawUrl = req.url ?? '/';
      if (/%|\\/.test(rawUrl) || rawUrl.split('?')[0].split('/').some(part => part === '.' || part === '..')) fail(404, 'Not found.');
      const url = new URL(rawUrl, 'http://relay.invalid');
      if (url.search) fail(404, 'Not found.');
      const parts = url.pathname.split('/').filter(Boolean), method = req.method ?? 'GET';
      let tenant = legacy;
      if (tenantMode && parts[0] !== 'assets') {
        if (url.pathname !== '/' + parts.join('/')) fail(404, 'Not found.');
        const index = parts[0] === 'api' && ['push', 'watch', 'output'].includes(parts[1]) ? 2 : ['watch', 'output', 'hls'].includes(parts[0]) ? 1 : -1;
        if (index < 0 || !WORKSPACE.test(parts[index] ?? '')) fail(404, 'Not found.');
        tenant = tenants.get(parts[index]); if (!tenant) fail(404, 'Not found.'); parts.splice(index, 1);
      }
      if (parts[0] === 'api' && parts[1] === 'push') {
        const slug = parts[2] ?? ''; validSlug(slug, tenant); authorize(req, tenant);
        const key = streamKey(tenant, slug), quotaKey = tenant.workspaceId ?? 'legacy';
        if (uploading >= 8 || tenantMode && (tenantUploads.get(quotaKey) ?? 0) >= 2) fail(429, 'Publishing is busy.'); uploading++; tenantUploads.set(quotaKey, (tenantUploads.get(quotaKey) ?? 0) + 1);
        try {
          if (method === 'POST' && parts.length === 4 && parts[3] === 'sessions') {
            const body = JSON.parse((await readBody(req, 1024)).toString('utf8'));
            if (typeof body.epoch !== 'string' || !EPOCH.test(body.epoch)) fail(400, 'A valid publishing epoch is required.');
            await serial(key, async () => {
              let record = streams.get(key);
              if (!record) {
                if (streams.size >= maxStreams || tenantMode && [...streams.keys()].filter(value => value.startsWith(`${tenant.workspaceId}/`)).length >= maxStreamsPerTenant) fail(429, 'Relay stream limit reached.');
                record = { epochs: [], session: null }; streams.set(key, record);
              }
              if (record.session?.epoch === body.epoch && record.session.endedAt === undefined) { send(res, 200, { sessionId: record.session.id }); return; }
              if (record.epochs.includes(body.epoch)) fail(409, 'This publishing epoch has ended.');
              const prior = record.session, current = { id: randomUUID(), epoch: body.epoch, startedAt: now(), files: new Map(), bytes: 0, sequence: -1, latest: -1n };
              await fs.mkdir(path.join(root, key), { recursive: true, mode: 0o700 });
              await fs.mkdir(path.join(root, key, current.id), { mode: 0o700 });
              record.session = current; record.epochs = [...record.epochs, body.epoch].slice(-64); await persist(key, record);
              if (prior) await fs.rm(path.join(root, key, prior.id), { recursive: true, force: true });
              send(res, 201, { sessionId: current.id });
            }); return;
          }
          const sessionId = parts[3] ?? '', filename = parts[4] ?? '';
          if (!SESSION.test(sessionId) || parts.length !== 5) fail(404, 'Not found.');
          const body = method === 'PUT' ? await readBody(req, filename === 'index.m3u8' ? 65536 : maxSegment) : await readBody(req, 1024);
          await serial(key, async () => {
            const current = streams.get(key)?.session;
            if (!current || current.id !== sessionId || current.endedAt !== undefined) fail(409, 'Publishing session is no longer current.');
            if (method === 'POST' && filename === 'end') { current.endedAt = now(); send(res, 200, { status: 'offline' }); return; }
            if (method !== 'PUT' || filename !== 'index.m3u8' && !SEGMENT.test(filename)) fail(404, 'Not found.');
            const folder = path.join(root, key, current.id);
            if (filename === 'index.m3u8') {
              const playlist = parsePlaylist(body);
              if (playlist.sequence < current.sequence || playlist.latest < current.latest) fail(409, 'An older live window cannot replace the current one.');
              if (playlist.segments.some(segment => !current.files.has(segment))) fail(409, 'Upload all media segments before publishing the playlist.');
              await atomic(path.join(folder, filename), body);
              if (playlist.latest > current.latest) current.lastProgressAt = now();
              Object.assign(current, { playlist: playlist.text, sequence: playlist.sequence, latest: playlist.latest });
              // Retain one preceding window for players already loading a segment.
              const minimum = BigInt(playlist.segments[0].slice(8, -3)) - 12n;
              for (const [name, info] of current.files) if (BigInt(name.slice(8, -3)) < minimum) { await fs.unlink(path.join(folder, name)).catch(() => {}); current.files.delete(name); current.bytes -= info.bytes; }
              send(res, 200, { status: state(streams.get(key)) }); return;
            }
            if (!body.length) fail(400, 'An empty segment is not valid.');
            const hash = digest(body), existing = current.files.get(filename);
            if (existing) { if (existing.hash !== hash) fail(409, 'Published media is immutable.'); send(res, 200, { bytes: body.length }); return; }
            if (current.files.size >= 32 || current.bytes + body.length > maxBytes) fail(413, 'Live window quota reached.');
            await atomic(path.join(folder, filename), body); current.files.set(filename, { hash, bytes: body.length }); current.bytes += body.length;
            send(res, 201, { bytes: body.length });
          }); return;
        } finally { uploading--; const count = (tenantUploads.get(quotaKey) ?? 1) - 1; if (count) tenantUploads.set(quotaKey, count); else tenantUploads.delete(quotaKey); }
      }
      if (parts[0] === 'api' && parts[1] === 'output' && parts.length === 4) {
        const slug = parts[2]; validSlug(slug, tenant);
        if (!tenant.privateSlugs.has(slug)) fail(404, 'Not found.');
        if (method === 'POST' && parts[3] === 'session') {
          if (!viewerKeyAccepted(req, tenant)) fail(401, 'Output access required. Open a current share link.');
          await readBody(req, 1024);
          const expires = now() + sessionMs, value = `v1.${expires}.${randomBytes(16).toString('hex')}`;
          // Native HLS and OBS receive the same HttpOnly cookie as fetch/Hls.js.
          // Name and MAC include workspace + slug; Path=/ covers API and HLS.
          // The only insecure exception is constructor-only, loopback-only tests.
          const localTest = options.allowInsecureLocalhostForTests === true && ['127.0.0.1', '::1', '::ffff:127.0.0.1'].includes(req.socket.remoteAddress);
          send(res, 200, { expiresAt: new Date(expires).toISOString() }, { ...outputHeaders(tenant, slug),
            'Set-Cookie': `${cookieName(tenant, slug)}=${value}.${signViewerSession(tenant, slug, value)}; Path=/; HttpOnly; SameSite=Strict; Max-Age=${Math.floor(sessionMs / 1000)}${localTest ? '' : '; Secure'}` }); return;
        }
        if (['GET', 'HEAD'].includes(method) && parts[3] === 'info') {
          authorizeViewer(req, tenant, slug);
          send(res, 200, { protected: true, ...(tenant.workspaceId ? { workspaceId: tenant.workspaceId } : {}), slug, watchUrl: route('output', tenant, slug), status: state(streams.get(streamKey(tenant, slug))) }, outputHeaders(tenant, slug)); return;
        }
        fail(404, 'Not found.');
      }
      if (!['GET', 'HEAD'].includes(method)) fail(405, 'Method not allowed.');
      if (parts[0] === 'api' && parts[1] === 'watch' && parts.length === 3) {
        const slug = parts[2]; validSlug(slug, tenant); authorizeViewer(req, tenant, slug); const record = streams.get(streamKey(tenant, slug)), status = state(record);
        send(res, 200, { status, ...(status === 'live' ? { playlistUrl: `${route('hls', tenant, slug)}/${record.session.id}/index.m3u8` } : {}) }, outputHeaders(tenant, slug)); return;
      }
      if (parts[0] === 'hls' && parts.length === 4) {
        const [, slug, sessionId, filename] = parts; validSlug(slug, tenant); authorizeViewer(req, tenant, slug); const key = streamKey(tenant, slug), current = streams.get(key)?.session;
        if (!SESSION.test(sessionId) || !current || current.id !== sessionId || state(streams.get(key)) !== 'live') fail(410, 'This live stream is offline.');
        if (filename !== 'index.m3u8' && (!SEGMENT.test(filename) || !current.files.has(filename))) fail(404, 'Not found.');
        const filenameOnDisk = path.join(root, key, sessionId, filename), stat = await fs.stat(filenameOnDisk);
        res.writeHead(200, { 'Content-Type': MIME[path.extname(filename)], 'Content-Length': stat.size, 'Cache-Control': filename === 'index.m3u8' ? 'no-store, max-age=0' : 'public, max-age=30, immutable', ...outputHeaders(tenant, slug) });
        if (method === 'HEAD') res.end(); else createReadStream(filenameOnDisk).on('error', () => res.destroy()).pipe(res); return;
      }
      let filename, privatePage = false;
      if (parts[0] === 'watch' && parts.length === 2) { validSlug(parts[1], tenant); authorizeViewer(req, tenant, parts[1]); privatePage = tenant.privateSlugs.has(parts[1]); filename = path.join(publicDir, 'watch.html'); }
      else if (parts[0] === 'output' && parts.length === 2) { validSlug(parts[1], tenant); if (!tenant.privateSlugs.has(parts[1])) fail(404, 'Not found.'); privatePage = true; filename = path.join(publicDir, 'output.html'); }
      else if (['/assets/watch.js', '/assets/watch.css', '/assets/output.js', '/assets/output.css'].includes(url.pathname)) filename = path.join(publicDir, path.basename(url.pathname));
      else if (url.pathname === '/assets/hls.min.js') filename = hlsBundle;
      else fail(404, 'Not found.');
      const stat = await fs.stat(filename), extension = path.extname(filename);
      res.writeHead(200, { 'Content-Type': extension === '.html' ? 'text/html; charset=utf-8' : extension === '.css' ? 'text/css; charset=utf-8' : 'text/javascript; charset=utf-8', 'Content-Length': stat.size, 'Cache-Control': privatePage ? 'private, no-store, max-age=0' : extension === '.html' ? 'no-store' : 'public, max-age=3600', ...(privatePage ? { Vary: 'Cookie, Authorization' } : {}) });
      if (method === 'HEAD') res.end(); else createReadStream(filename).on('error', () => res.destroy()).pipe(res);
    } catch (error) { if (!res.headersSent) send(res, error instanceof HttpError ? error.status : error instanceof SyntaxError ? 400 : 500, { error: error instanceof HttpError ? error.message : error instanceof SyntaxError ? 'Invalid JSON.' : 'Relay request failed.' }); else res.destroy(); }
  });
  server.on('close', () => clearInterval(interval));
  return { server, cleanup, close: () => new Promise((resolve, reject) => { clearInterval(interval); server.close(error => error ? reject(error) : resolve()); server.closeIdleConnections(); }) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tenants = process.env.LUMEN_WATCH_TENANTS_FILE !== undefined ? await readTenantRegistry(process.env.LUMEN_WATCH_TENANTS_FILE) : undefined;
  const relay = await createWatchRelay({ dataDir: process.env.LUMEN_WATCH_DATA_DIR ?? path.join(process.cwd(), 'data'), tenants, pushToken: process.env.LUMEN_WATCH_PUSH_TOKEN, allowedSlugs: process.env.LUMEN_WATCH_SLUGS?.split(',').map(value => value.trim()).filter(Boolean), privateSlugs: process.env.LUMEN_WATCH_PRIVATE_SLUGS?.split(',').map(value => value.trim()).filter(Boolean), viewerToken: process.env.LUMEN_WATCH_VIEWER_TOKEN });
  const port = Number(process.env.PORT ?? 3480), host = process.env.HOST ?? '127.0.0.1';
  relay.server.listen(port, host, () => console.log(`Lumen Watch relay listening on ${host}:${port}`));
  for (const signal of ['SIGTERM', 'SIGINT']) process.once(signal, () => { void relay.close().finally(() => process.exit()); });
}

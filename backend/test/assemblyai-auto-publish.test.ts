import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import WebSocket from 'ws';
import {WorshipLibrary} from '../src/worship-library.js';
import {ListeningSessions} from '../src/listening-session.js';
import {createAssemblyBridge} from '../src/assemblyai-bridge.js';
import type {AssemblyTurn} from '../src/assemblyai-stream.js';

test('AssemblyAI auto publish requires a new finalized match, respects manual disarming and never publishes during stop',async t=>{
 const library=new WorshipLibrary(':memory:');
 library.importBible({version:{id:'KJV',name:'KJV',attribution:'test'},verses:[16,17,18].map(verse=>({book:43,chapter:3,verse,text:verse===16?'For God so loved the world that he gave his only begotten Son.':'Test verse '+verse}))});
 const sessions=new ListeningSessions(library,()=>{});
 const lease=sessions.start('scripture','operator',{provider:'assemblyai',mode:'automatic',language:'en',commands:false});
 let turn!:(value:AssemblyTurn)=>void;
 const bridge=createAssemblyBridge({sessions,library,drainOnStop:true,key:async()=> 'test',authorize:()=>{sessions.check('scripture',lease.id,'operator');return 'operator';},createStream:(_key,onTurn)=>{turn=onTurn;return {connected:Promise.resolve(),send:()=>{},finish:()=>{},close:()=>{}};}});
 const server=http.createServer();server.on('upgrade',(req,socket,head)=>bridge.wss.handleUpgrade(req,socket,head,ws=>bridge.wss.emit('connection',ws,req)));
 await new Promise<void>(resolve=>server.listen(0,'127.0.0.1',resolve));
 const socket=new WebSocket(`ws://127.0.0.1:${(server.address() as any).port}/?channel=scripture&session=${lease.id}`),messages:any[]=[];
 socket.on('message',value=>messages.push(JSON.parse(String(value))));
 t.after(async()=>{socket.terminate();bridge.stop('scripture');bridge.wss.close();await new Promise<void>(resolve=>server.close(()=>resolve()));library.close();});
 const wait=async(fn:()=>boolean)=>{const deadline=Date.now()+3000;while(!fn()){if(Date.now()>deadline)throw Error('Timed out');await new Promise(r=>setTimeout(r,5));}};
 await wait(()=>messages.some(m=>m.type==='ready'));
 const emit=async(order:number,text:string,final:boolean,confidence?:number)=>{const count=messages.filter(m=>m.type==='result').length;turn({type:'Turn',turn_order:order,transcript:text,end_of_turn:final,...(confidence===undefined?{}:{words:[{text,start:0,end:100,confidence}]})});await wait(()=>messages.filter(m=>m.type==='result').length>count);return messages.filter(m=>m.type==='result').at(-1).result;};
 assert.equal((await emit(0,'John chapter three verse sixteen',false)).switched,false);
 assert.equal(library.workspace('scripture').live,null);
 assert.equal((await emit(0,'John chapter three verse seventeen',true)).decision,'sent-live');
 assert.equal((await emit(0,'John chapter three verse eighteen',true)).switched,false,'revised final cannot republish a completed turn');
 assert.equal((await emit(1,'John chapter three verse eighteen',true,.4)).switched,false,'low-confidence provider words need review');
 assert.equal((await emit(2,'For God so loved',true)).switched,false,'partial quotation cannot publish');
 sessions.disarm('scripture');
 assert.equal((await emit(3,'John chapter three verse eighteen',true)).switched,false,'manual disarm preserves capture but prevents publishing');
 sessions.check('scripture',lease.id,'operator').mode='automatic';
 assert.equal((await emit(4,'John chapter three',true)).switched,false);
 assert.equal((await emit(5,'Verse sixteen',false)).switched,false);
 assert.equal((await emit(5,'Verse sixteen',true)).decision,'sent-live','a finalized chapter survives the following turn’s provisional words');
 bridge.finish('scripture');
 assert.equal((await emit(6,'John chapter three verse eighteen',true)).switched,false,'drained final words are transcript-only');
 assert.equal(library.workspace('scripture').live?.selection.kind,'scripture');
 assert.equal((library.workspace('scripture').live?.selection as any).verse,16);
});

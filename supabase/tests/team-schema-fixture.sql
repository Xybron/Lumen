-- ONLY a disposable PostgreSQL container fixture, never run against LAB.
-- These small Auth/Realtime stubs let tests exercise SQL privileges and RLS;
-- they are not substitute Auth accounts or part of the migration.
create role anon nologin;
create role authenticated nologin;
create schema auth;
create table auth.users(id uuid primary key, deleted_at timestamptz, banned_until timestamptz, email_confirmed_at timestamptz, phone_confirmed_at timestamptz);
create table auth.sessions(id uuid primary key, user_id uuid references auth.users(id), not_after timestamptz);
create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb); $$;
create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid; $$;
grant usage on schema auth to authenticated;
grant execute on function auth.jwt(), auth.uid() to authenticated;
create schema realtime;
create table realtime.messages(id bigint generated by default as identity primary key, extension text);
alter table realtime.messages enable row level security;
create function realtime.topic() returns text language sql stable as $$ select current_setting('realtime.topic', true); $$;
grant usage on schema realtime to authenticated;
grant select, insert on realtime.messages to authenticated;
grant usage on sequence realtime.messages_id_seq to authenticated;
grant execute on function realtime.topic() to authenticated;

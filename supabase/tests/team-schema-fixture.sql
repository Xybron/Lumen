create function public.test_claims(p_suffix text) returns void language plpgsql as $$
begin
 perform set_config('request.jwt.claims',jsonb_build_object('sub','00000000-0000-4000-8000-'||p_suffix,'session_id','10000000-0000-4000-8000-'||p_suffix,'exp',extract(epoch from now())::bigint+3600,'is_anonymous',false)::text,false);
end;
$$;
create function public.test_assert(p_ok boolean, p_message text) returns void language plpgsql as $$
begin if p_ok is not true then raise exception 'Assertion failed: %',p_message; end if; end; $$;
create function public.test_reject(p_sql text, p_state text) returns void language plpgsql as $$
begin
 begin execute p_sql; exception when others then
   if sqlstate = p_state then return; end if;
   raise exception 'Expected SQLSTATE %, got %: %',p_state,sqlstate,sqlerrm;
 end;
 raise exception 'Expected rejection (%), but query succeeded: %',p_state,p_sql;
end;
$$;
